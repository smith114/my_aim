#!/usr/bin/env bash
# ============================================================================
#  实车开火
#
#  前置: 已经用 1_调参.sh 调好并按 s 保存过参数。
#
#  流程图:
#    遥控器开自瞄  ->  mode 变 1  ->  锁定装甲板  ->  [FIRE] 开火(我们发请求)
#                                                          |
#                                                          v
#                                                   你按人工许可 -> 出弹
#
#  规则要求: fire_flag 只是视觉侧请求, 实际发射还需【火控允许】+【人工许可】。
# ============================================================================
set -uo pipefail
cd "$HOME/myaim" || exit 1

pkill -f 'build/' 2>/dev/null
sleep 1

mkdir -p logs
LOG="logs/fire_$(date +%Y%m%d_%H%M%S).log"

echo "=============================================================="
echo "  自瞄 + 开火"
echo "--------------------------------------------------------------"
echo "  1) 遥控器打开自瞄 —— 必须看到 mode=1"
echo "  2) 手动对准靶标, 等 locked=1"
echo "  3) 等终端打出 [FIRE] 开火  (这是我们的开火请求)"
echo "  4) 按人工许可键 -> 子弹才出膛"
echo
echo "  终端第一屏会打印 [EFFECTIVE], 那是本次实际生效的全部参数,"
echo "  确认 offset / dir 是你调的值。"
echo
echo "  日志同时写入: $LOG"
echo "  Ctrl-C 退出"
echo "=============================================================="

./build/my_aim --fire --debug 2>&1 | tee "$LOG"
