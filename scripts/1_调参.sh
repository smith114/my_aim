#!/usr/bin/env bash
# ============================================================================
#  可视化调参 / 调试
#
#  用途: 看检测框、收发量、锁定状态，用滑条现场调参。
#        调好之后**必须按 s 保存**，否则 my_aim 读不到。
#
#  界面: camera(图传+检测框+光轴十字) / params(收发量+参数) / knobs(滑条)
#  按键: s=保存参数  r=重新加载  q或Esc=退出
# ============================================================================
set -uo pipefail
cd "$HOME/myaim" || exit 1

# 同一时间只能有一个程序占用相机和串口
pkill -f 'build/' 2>/dev/null
sleep 1

echo "=============================================================="
echo "  可视化调参"
echo "--------------------------------------------------------------"
echo "  三个窗口会弹出来:"
echo "    camera  图传 + 检测框(绿=选中) + 绿色十字(光轴中心)"
echo "    params  发出去什么 / 收到什么 / 差多少 / 当前参数"
echo "    knobs   所有可调滑条"
echo
echo "  常用滑条:"
echo "    conf        置信度, 漏检就降 / 误检就升"
echo "    enemy       0=蓝 1=红 2=不过滤"
echo "    off yaw     (100=0度) 落点偏右就加大"
echo "    off pitch   (100=0度) 落点偏低就加大"
echo "    dirYaw/dirPitch  伺服方向, 0=-1 1=+1"
echo "    gain        增益, 抖就降"
echo "    deadband    死区(度x10)"
echo "    measLP      实测角低通(8~14 是合理区间)"
echo
echo "  >>> 调好后按 s 保存到 aim_params.cfg <<<"
echo "  >>> 按 q 或 Esc 退出 <<<"
echo "=============================================================="

./build/aim_gui
