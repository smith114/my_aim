// 之后连反向命令(-20度)都不再响应, 只能断电重启。
// 所以命令角一律限制在 [MIN+MARGIN, MAX-MARGIN] 之内, 永不贴边。
constexpr float GIMBAL_PITCH_MARGIN = 2.0f;
constexpr float GIMBAL_PITCH_MIN = -35.8f;   // 实测机械下限
constexpr float GIMBAL_PITCH_MAX =  26.1f;   // 实测机械上限

// ============================================================ 无目标时的行为
// **默认不摆扫。** 这一条是实测踩坑之后定的。
