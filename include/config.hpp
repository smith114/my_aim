constexpr bool  KF_LEAD_FLIGHT_TIME = true;

// ******** 提前量只作用在 yaw 轴 ********
//
// 实测(10-29): 加了飞行时间补偿后 pitch 自激。
//   pitch 提前量: -4.06 -> -9.58 -> -10.63
//   pitch 角速度: -7.84 -> -12.93 -> -14.70
//   fb pitch    : -3.9 -> -10.6 -> -8.2        <- 云台真的低头了
// 闭环: 角速度噪声 -> 提前量 -> 云台动 -> theta 变 -> 角速度更大 -> ...
// **云台自己制造了它要补偿的运动。**
//
// 物理依据: 旋转靶绕**竖直轴**转, pitch 方向没有真实运动。
// 该轴上的角速度估计只可能是噪声或自激, 所以**不推**, 让它老老实实跟当前测量。
// yaw 轴有真实的横扫运动, 提前量必须保留。
constexpr bool  KF_LEAD_PITCH = false;

// ******** 提前量低通 ********
//
// 实测(10-30): yaw 的提前量在 +3.84 -> -5.79 -> +2.70 之间逐帧翻号,
// 因为角速度估计本身就在 ±10 度/秒 之间跳。提前量一跳, 云台就跟着摆,
// 表现就是"一直在晃、锁不住"。
//
// 但转速是**慢变量** —— 靶标不会在 10ms 内改变转向。所以对提前量本身做低通
// 是物理上正确的: 保留平均提前量(解决打空隙), 去掉逐帧抖动(解决晃动)。
//
// 0.10 -> 时间常数约 10 帧(100fps 下 0.1 秒), 远快于转速的真实变化,
// 又足以滤掉逐帧噪声。
constexpr float KF_LEAD_LP_COEF = 0.10f;

// ******** 云台自己没跟上时, 抑制提前量 ********
//
// 问题(10-30, 操作手原话): "切换装甲板时转过去后, 此时装甲板已经移动到下一个
// 瞬时, 导致需要回正, 引发轻微抽动"。
//
// 机制: 提前量 lead = omega * T 的前提是 **theta 的变化只来自目标运动**。
// 换板时命令突然跳几度, 云台正以每帧几度的速度追赶, 此刻 theta 快速变化
// 主要来自**云台自己**, 卡尔曼把它当成目标运动 -> 角速度估计虚高
// -> 提前量偏大 -> 转到位时已经越过目标 -> 回正 -> 抽动。
//
// 判据: 跟随误差 |cmd - fb| > 此值 就认为"云台在追赶中", 提前量目标置 0。
// 用低通平滑衰减(不是硬切), 所以不会引入新的台阶。
// 1.5 度: 正常稳态跟随误差约在 SERVO_MAX_CORR_DEG(6) 之内但通常 <1 度,
// 1.5 度只在换板/大偏差时被超过。
constexpr float KF_LEAD_SUPPRESS_DEG = 1.5f;

// ******** 盯圆心策略(操作手提出, 物理上正确) ********
//
// 原策略"追当前最优板"要求精确预测转速和相位, 任何误差都变成打进两块板
// 之间的空隙 —— 实测低速靶 75%, 高速完全不行。
//
// 新策略: 云台**盯住靶标旋转中心的方位**, 板转到正面时会自己经过这个方位,
// 此时开火。
//
// 物理依据: 板装在半径 R 处绕竖轴转, 其方位偏移 = atan(R*sin(phi)/d)。
//   phi=0(正对镜头) 时偏移为 0 -> **板正对时方位恰好等于圆心方位**。
// 精度依据: 圆心附近 d(theta)/d(phi) = R/d 很小。
//   R=0.2, d=5 时 0.04, 飞行 0.24s 内转 7.2 度只造成 0.29 度方位误差,
//   而板宽 1.5 度 —— 容差天然宽 5 倍, 不需要精确转速。
//
// 附带好处: 云台几乎静止, 于是"提前量翻号""追赶时角速度虚高""过冲回正"
// 这些**追板才有的问题全部消失**。
constexpr bool  CENTER_HOLD_ENABLE = true;

// 圆心方位的低通系数。板在圆心两侧摆动, 慢速平均即得圆心。
// 0.015 在 110fps 下时间常数约 0.6 秒 —— 远长于单块板经过的时间(约 0.3s),
// 又远短于操作手手动改变瞄准的时间。
constexpr float CENTER_LP_COEF = 0.015f;

// ******** 用旋转模型预测"板什么时候经过瞄准点" ********
//
// 操作手指出: 这是一个 4 装甲板匀速旋转模型, 知道一块就能推其余, 跟踪的板
// 状态不好时应该用模型预测而不是丢目标。同济的 target.cpp 正是这个思路
// (拟合圆心/半径/转速, 某块板看不见时用模型补)。
//
// 完整三维模型我们试过(11 维 EKF), 精度 1.53 度不够。但**不需要三维**:
// 板相对圆心的方位偏差 pos_dev 是一个**正弦**, 只要知道它此刻的值和变化率,
// 就能外推到子弹到达时刻:
//     pos_dev_pred = pos_dev + d(pos_dev)/dt * t_flight
//
// 这正是"填补飞行时间"的预测, 但作用在**偏差**上而不是板的绝对方位,
// 所以不引入追板的那些误差。已知 5m/22m/s 飞行约 0.24 秒,
// 30 度/秒转速下偏差只变约 0.25 度(板宽 1.5 度), 线性外推足够准。
constexpr bool  CENTER_PRED_ENABLE = true;

// 偏差变化率的低通系数(0.25 -> 约 4 帧, 快速响应又不至于被单帧噪声带跳)
constexpr float CENTER_DEV_RATE_LP = 0.25f;

// ******** 换板时不增加补偿 ********
//
// 要求: "切换目标不增加补偿, 保证平滑切换锁定"。
// 换板时 theta 会突跳 5~7 度(两块板的方位差), 卡尔曼若把它当真实运动,
// 角速度估计会跳一下 -> 提前量在那一帧突变 -> 表现为"切换时多给了补偿"。
//
// 判据: 选中的候选下标变了, 或 theta 单帧跳变超过此值 -> 判定换板。
// 动作: 重置两轴滤波器(连带把提前量清零), 并让重捕获后的前几帧不外推
//       (kf.hpp 的 rate_trusted() 需要 5 帧才信任速度)。
constexpr float KF_SWITCH_JUMP_DEG = 4.0f;

// 提前量上限(度)。原来 kf.hpp 里写死 8 度, 对旋转靶不够:
//   307ms 内 30 度/秒就转 9 度, 高速档更多。
// 提高到 25 度, 仍能挡住"角速度估计炸了"的异常外推。
constexpr float KF_MAX_LEAD_DEG = 25.0f;

// 飞行时间的弹速兜底(裁判系统未接入时用)
// 与 BULLET_SPEED_DEFAULT 一致, 改一个就行
// 过程噪声与测量噪声。R 应由"静止靶标时 theta 的抖动标准差"实测。
constexpr float KF_Q_ANGLE  = 1e-2f;
// **保持 10, 不降**。
// 试过降到 1.0 来压制"换板造成的假速度", 但 test_kf 立刻报错:
// 合成匀速目标(无噪声)的预测误差从 0.004 度变成 4.24 度 —— 滤波器跟不动
// 真实速度了。这说明**不该用牺牲滤波器能力的方式去补偿坏输入**,
// 应该修输入(选板迟滞, 见 SELECT_SAME_TARGET_DEG)。
constexpr float KF_Q_RATE   = 1e1f;
constexpr float KF_R_ANGLE  = 0.5f;
// 估计角速度达到该值才认为"目标在动"(用于开火判据的额外保守)
constexpr float KF_MOVING_RATE_DPS = 3.0f;

// ---- 瞄准偏差补偿(相机/枪口安装不平行) ----
//
// theta 是**相机系**的偏角, 而命令角是**云台系**的。两者之间差一个安装外参:
// 相机光轴与云台瞄准轴不平行、相机不在云台旋转中心。物理上这是一个常值旋转,
// 表现就是"theta 算到 0 了, 但枪口并没对准目标"。
//
// 参考实现用 yaw_offset / pitch_offset 两个度数补偿同一件事。
//
// **怎么标定**: 手动把云台对准靶标中心(肉眼确认板在画面正中), 然后读日志里
// 稳定后的 th 值, 把它的相反数填到这里。例如 th 稳定在 -1.2/0.8,
// 就填 AIM_YAW_OFFSET_DEG = +1.2, AIM_PITCH_OFFSET_DEG = -0.8。
//
// 这是目前**唯一还没标定**的量。它不影响收敛, 只影响最终停在哪。
// **5 米现场标定值**(2026-10-29 实测: 静止靶 100%, 低速旋转 75%)
constexpr float AIM_YAW_OFFSET_DEG   = 0.0f;
// 3.7 度 = 枪口在相机下方的安装偏差 + 5m 处重力下坠 253mm 的合成补偿。
// 这是打中 5 米靶的关键常量, 改动前务必重新打靶验证。
constexpr float AIM_PITCH_OFFSET_DEG = 3.7f;

// **现场定为 0.80**（2026-10-30，操作手在 GUI 里逐档试出来的）。
// 1.0 时回路在"增益 × 滞后"下进入极限环: 实测 cmd 自己摆 ±2 度、周期约 1 秒,
// 而 theta 只有 ±1.5 度 —— 是回路在振, 不是目标在拽。降到 0.80 抽动消失,
// 而跟上旋转靶仍够快。
// 滞后来源: meas_lp_coef 0.10(约 10 帧) + smooth 0.35(约 3 帧)。
constexpr float SERVO_GAIN      = 0.80f;   // 偏差角 -> 需要转过的角度 的比例
// 单帧**修正量**上限(度)。这是控制律里唯一的限幅, 直接决定"逼近速度":
//   |theta| <= 该值 -> 一帧到位
//   |theta| >  该值 -> 每帧最多修这么多, 分段逼近(不会一次甩出去)
// 实测教训(10-28): 原来按 2 度/帧 在累积命令上做限制, 云台冲过头 30 多度把板甩出画面。
// 现在恒速冲是不可能的, 因为命令永远是 "实测角 + 有限修正"。
constexpr float SERVO_MAX_CORR_DEG = 6.0f;

// ******** 命令变化率限制(消抽动) ********
//
// 实测(10-29): 跟踪还行但会"不时抽动"。原因是一帧的异常 theta
// 会产生最大 SERVO_MAX_CORR_DEG(6 度)的修正 -> 云台猛顿一下。
//
// 注意这和**已废弃**的写法不同:
//   废弃的: cmd = step_toward(cmd, want, 2)  -> cmd 自己累积前进, meas 追不上 -> 过冲
//   这里的: cmd 仍 = meas_lp + 修正, 只限制"相对上一帧命令"的变化量
// 稳态下正常变化本来就 <3 度, 所以不影响跟踪; 只削掉单帧突跳。
constexpr float SERVO_CMD_SLEW_DEG = 3.0f;   // 每帧命令最大变化(度)   // 分 4~5 段追上 25 度的大偏角
// 软启动帧数: 进跟踪后增益从 0 线性升到 SERVO_GAIN。
// 目的: 切换视觉模式的那一刻, 如果目标偏角较大, 不要一上来就满增益猛转。
// 20 帧 @ 约 16fps 约 1.2 秒, 足够平缓又不至于明显迟钝。
constexpr int   SERVO_SOFT_START_FRAMES = 20;
constexpr float GIMBAL_SMOOTH   = 0.35f;  // 偏差角低通系数
// ******** 死区: 已按轴区分 ********
//
// 实测(10-29): 死区设 0 之后 **pitch 方向上下抖**。
// 原因是物理的: 旋转靶绕**竖直轴**转, pitch 方向没有真实运动,
// theta_pitch 全是检测噪声; 死区为 0 就等于让纯噪声直接驱动伺服。
// yaw 有真实运动, 不需要死区。
//
// 现场取值: pitch 0.3 度。5m 处 0.3 度 = 26mm, 而板宽 140mm,
// 精度损失可忽略, 但能消掉小噪声引起的抖动。
constexpr float GIMBAL_DEADBAND      = 0.0f;   // yaw 轴
constexpr float GIMBAL_DEADBAND_PITCH = 0.3f;  // pitch 轴(无真实运动, 只需抑制噪声)   // 现场定为 0(有 measLP 低通就够, 死区反而影响精度)   // 死区(度), 消极限环摆动
constexpr float GIMBAL_MANUAL_STEP = 1.5f;// 手动控制步长(度/次)

// 安全包络: 命令角离"启动姿态"最远允许多少度。
//
// 为什么要这一层: 云台 yaw 能整圈转, 但 pitch 有机械限位, 而**零位并不是机壳
// 行程的中点** —— 实测进视觉模式时 pitch=-38.3 度, 可机械行程只有约
// [-35.8, +26.1] (见下), 两者对不上, 所以"绝对区间"不能照抄测量值。
// 相对启动姿态限制则与零位无关, 是安全且可移植的做法。
//
// 一旦 pitch 顶到限位: 反馈会卡住不再跟随命令, 此时如果还按"绝对区间"去比较,
// 会算出一个错误的高度差, 云台就卡死在错的高度回不来。相对包络没有这个问题。
//
// 这个值同时决定摆扫寻板的搜索范围, 需要 >= GIMBAL_SCAN_AMP/2。
// 丢目标后朝启动姿态回中的速率(度/秒)。太大会猛跳, 太小会长时间看不到靶标。
// 8 度/秒: 从天花板(pitch -35)回到水平(0)约 4.4 秒, 观感平滑且能自救。
constexpr float GIMBAL_RECENTER_DPS = 8.0f;

// ******** 活动包络: 已**关闭** ********
//
// 原来设 30 度, 意思是"命令角相对启动姿态不超过 30 度", 目的是防止云台甩飞。
// 但它连着出了三次问题, 每次都是同一个原因: home 锚在哪就框死在哪里。
//   - home 冻结在启动姿态, 操作手手动改方向后靶标跑到框外 -> 命令被夹住
//   - 启动时没对准, 之后无论怎么调都追不到
//   - home 曾算到 -38.3 (低于机械下限 -35.8), 可用范围只剩 25 度且全部朝上
//
// 复核安全问题: 去掉包络后仍有两道硬约束,
//   1) pitch 的**机械行程** clamp [-33.8, +24.1](含 2 度余量) —— 这防撞限位
//   2) 发散保护: |theta| 连续 40 帧增大就停机报警 —— 这防跑飞
// 而 yaw 本来就是整圈自由轴, 不需要框。
// 所以包络在这里没有它保护的独占风险, 只有"夹住合法命令"的副作用。
constexpr float GIMBAL_ENVELOPE_DEG = 180.0f;

// ============================================================ 云台量程
// 实机确认(2026-10-16):
//   yaw   : 左右 360 度全向, 无机械限位 -> 按 wrap 处理
//   pitch : **上下有限**, 实测机械行程约 [-35.8, +26.1] 度 (以视觉模式零位为参考)
//           命令继续增大时反馈卡住不动 = 顶到限位
//
// **pitch 的上下限就是实测机械行程, 不是数值保护。**
// 之前这里写的是 [-180, 180] 并注明"数值保护", 结果跨度正好 360, 让
// wrap_or_clamp_pitch 走进了 wrap 分支: -30 度被归一成 330 度发下去,
// 云台顶死机械限位。现在改成真实行程并强制 clamp。
//
// 为什么把实测行程写死是安全的: 相对包络(±GIMBAL_ENVELOPE_DEG)本身也有
// 同样的问题 —— home 靠近上限时对称包络会越过行程(实测 home=+25 时包络上限
// 是 +55, 超出机械上限 28.9 度), 云台照样顶死。用绝对行程硬限是唯一能真正
// 挡住这种情况的手段。两道限制叠加: 相对包络管"别离瞄准点太远",
// 绝对行程管"别顶到限位"。
//
// 风险与前提: 这两个数依赖下位机 pitch 零点不变。若以后零点被重新标定
// (比如换了固件/重新上电归零方式变了), **必须重新实测行程并更新这两个值**,
// 否则云台会在错误的高度上被限制住。测法: gimbal_test --sweep ±pitch --stop N
constexpr float GIMBAL_YAW_MIN   = 0.0f;
constexpr float GIMBAL_YAW_MAX   = 360.0f;   // >= 359 视为整圈(wrap)
// **留安全余量**: 命令角不要贴着行程末端发。
