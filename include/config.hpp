// ============================================================ 开火判据
//
// 规则约束: 上位机只能通过 ID2 的 fire_flag 表达"建议开火"; **人工发射许可由鼠标
// 左键给出, 由下位机实现**。所以这里是"建议", 不是"决定", 双保险。
//
// 需要连续锁定多少帧才允许开火。取 8 帧(约 0.15~0.5 秒):
// 太短会在检测抖动时误开火, 太长会错过旋转靶标的窗口。
// 从 8 降到 3。
// 实测(10-30): 旋转靶的检测是**间断**的 —— 板转到侧面就丢几帧, state 在
// TRACK/LOST 之间来回。要求"连续 8 帧都锁定"永远达不到, 于是永久停火。
// 3 帧(约 50ms)足以排除单帧误检, 又不会因为正常丢帧就清零。
// 赛制要求: 1 分钟打 50 发 = 0.83 发/秒, 所以 fire_flag 必须**尽量长时间保持 1**,
// 而不是一闪一闪。掉帧/单帧丢板会让条件短暂失效, 火控那边会因此重新计时,
// 吞吐直接砍半。所以条件失效后再保持这么几帧(约 30ms), 骑过单帧丢板。
constexpr int   FIRE_LOCK_FRAMES     = 2;    // 2 帧(约 20ms)足以排除单帧误检
constexpr int   FIRE_HOLD_FRAMES     = 3;    // 条件失效后再保持 3 帧, 骑过丢板

// 容差 = 系数 × 装甲板在当前距离下的**角宽度**。
// 板宽 140mm, 角宽 = 2*atan(0.07/dist)。取 0.6 表示"只打板中央 60%",
// 留 40% 余量吸收预测误差和弹道散布。
// 从 0.6 放到 0.8(打板中央 80%)。
// 实测(10-30): 5.5m 处板角宽 1.41 度, 0.6 倍容差只有 0.84 度,
// 而 yaw 的摆动本身就有 ±1 度(板在转), 于是经常判超差。
// 0.8 倍 = 1.13 度 = 98mm, 仍在 125mm 板高之内。
// **从 0.8 收到 0.55**（2026-10-30 实测有概率打空隙）。
//
// 0.8 时 5m 处容差 1.24 度 = 允许瞄准点离**板心** 54mm, 而板半宽只有 67.5mm
// —— 已经贴着边缘, 加上弹道散布就落到两板之间。
// 而板正对时方位在容差内停留最久, 所以多数射击恰恰发生在"刚进容差"、
// 偏得最多的位置。
//
// 0.55 -> 0.85 度 = 离板心 37mm, 稳稳在板内。
// 代价: 开火窗口从 74% 降到约 48%((|sinphi| <= 0.37) -> |phi| <= 22 度,
// 每板 43 度, 4 板 172/360)。对"1 分钟 50 发 = 0.83 发/秒"仍然充足。
// ******** 这个系数是"全宽"的比例, 与容差是【半角】这件事容易搞混 ********
//
// plate_angular_width_deg() 返回板在 5m 处的**全宽** 1.55 度, 即半角 0.77 度。
// 而 fire_tolerance_deg() 的值是**半角**(允许瞄准点偏离板心多少)。
// 所以系数 > 0.5 就意味着允许偏出板外。
//
// 实测教训(2026-10-30): 先设 0.8, 容差 1.24 度 = 离板心 108mm,
// 而板半宽只有 67.5mm —— **允许多偏出半个板宽**, 于是有概率打进两板之间。
// 再设 0.55 仍然 74mm, 还是出板。
//
// 现在 0.45 -> 0.70 度 = 离板心 61mm, 稳稳在 67.5mm 半宽之内。
// 占空比: |sinphi| <= 0.70/2.3 = 0.30 -> |phi| <= 17.5 度, 每板 35 度,
//        4 板 = 140/360 = 39%。对"1 分钟 50 发 = 0.83 发/秒"仍充足。
// ******** 0.45：实测最优, 不要动 ********
//
// 2026-10-30 实测: 0.45 时 25 发/30 秒、命中 80%(20/25)。
//
// 试过收紧到 0.25（想把落点从侧面移到正中），结果**双输**:
// 发数变少, 而且**更容易进空隙**。
// 这否定了"火控在窗口入口就开火导致偏侧"的假说, 说明真因是
// **圆心估计本身有系统偏差**(检测窗口相对 phi=0 不对称, 板的方位平均值被带偏)。
//
// 关键推论: **收紧容差无法修正偏置**。偏置还在, 收紧只是让射击更少、
// 而且更集中在那个"偏的位置"上, 所以反而更容易出板。
//
// 想真正把落点移到正中, 必须换**无偏的圆心估计**(一个周期内摆动的中点,
// 或对 theta 做正弦拟合取直流分量), 那是代码改动, 不在终验前做。
constexpr float FIRE_TOL_FRAC        = 0.45f;