//
// 需要连续锁定多少帧才允许开火。取 8 帧(约 0.15~0.5 秒):
// 太短会在检测抖动时误开火, 太长会错过旋转靶标的窗口。
// 从 8 降到 3。
// 实测(10-30): 旋转靶的检测是**间断**的 —— 板转到侧面就丢几帧, state 在
// TRACK/LOST 之间来回。要求"连续 8 帧都锁定"永远达不到, 于是永久停火。
// 3 帧(约 50ms)足以排除单帧误检, 又不会因为正常丢帧就清零。
constexpr int   FIRE_LOCK_FRAMES     = 3;

// 容差 = 系数 × 装甲板在当前距离下的**角宽度**。
