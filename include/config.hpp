constexpr bool  KF_ENABLE   = true;
// 需要实测: 用"云台匀速扫 + 比对命令角与实测角相位差"测, 或拍闪烁 LED 比对时间戳。
// 先用 80 ms, 测出来再改。
constexpr float KF_LATENCY_S = 0.080f;

// ******** 弹丸飞行时间补偿 ********
